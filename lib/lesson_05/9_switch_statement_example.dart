void main() {
  final day = 'середа';

  switch (day) {
    case 'понеділок':
      print('Початок тижня');
    case 'пʼятниця':
      print('Кінець робочого тижня');
    // можна ще ось так
    // case 'субота' || 'неділя':
    case 'субота':
    case 'неділя':
      print('Вихідний');
    default:
      print('Звичайний робочий день');
  }
}
