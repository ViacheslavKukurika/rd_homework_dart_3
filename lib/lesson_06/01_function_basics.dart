/// Основи функцій: без параметрів, з параметрами, повернення значень
///
/// Таблиця всіх варіантів параметрів:
/// | Синтаксис              | Що означає                     | Приклад виклику                    |
/// |------------------------|---------------------------------|------------------------------------|
/// | (a, b)                 | обовʼязкові позиційні           | f(1, 2)                            |
/// | ([a?, b?])             | опціональні позиційні (null)    | f() / f(1) / f(1, 2)               |
/// | ([a = 1, b = 2])       | опціональні з дефолтом          | f() / f(3) / f(3, 4)               |
/// | ({required a, required b}) | іменовані обовʼязкові       | f(a: 1, b: 2)                      |
/// | ({a?, b?})             | іменовані опціональні (null)    | f() / f(a: 1) / f(b: 2)            |
/// | ({a = 1, b = 2})       | іменовані з дефолтом            | f() / f(a: 3) / f(b: 4)            |
/// | (a, b, [c?, d?])       | позиц. обовʼязкові + опціон.    | f(1, 2) / f(1, 2, 3)               |
/// | (a, b, {c?, d?})       | позиц. обовʼязкові + іменов.    | f(1, 2) / f(1, 2, c: 3)            |
///
int multiply(int a, int b) {
  return a * b;
}

String getGreeting() {
  return 'Доброго дня!';
}

void sayHello() {
  print('Привіт !');
}

void sayHelloTo(String name) {
  print('Привіт, $name!');
}

void functionBasicsExample() {
  print('🔧 Основи функцій');

  // Функція без параметрів і без повернення
  sayHello();

  // Функція з параметром
  sayHelloTo('Марія');

  // Функція що повертає значення
  print('4 * 5 = ${multiply(4, 5)}');

  // Результат можна зберегти в змінну
  final greeting = getGreeting();
  print(greeting);
}

void main() => functionBasicsExample();
